using UnityEngine;

//==============================================================================
// BossUnit
//==============================================================================
// 보스 유닛 클래스. EnemyUnit을 상속하며 사망 시 게임 클리어 패널을 표시한다.
//==============================================================================
public class BossUnit : EnemyUnit
{
    //-------------------------------------------------------------------------
    // 사망 처리
    //-------------------------------------------------------------------------
    public override void Dead()
    {
        base.Dead();
        // 보스가 쓰러지면 게임 클리어 패널 표시
        AllManager.instance.UIManager.GameClearPage();
    }
}
