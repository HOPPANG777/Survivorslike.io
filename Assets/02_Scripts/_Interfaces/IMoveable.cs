using UnityEngine;

//==============================================================================
// IMoveable
//==============================================================================
// 객체중에 이동하는 객체가 있다면 해당 인터페이스를 상속받아 구현
// 캡슐화를 위한 인터페이스
//==============================================================================
public interface IMoveable
{
    // 객체의 이동방향
    public Vector3 MoveDirection { get; set; }

    // 객체의 이동
    public void Move();
}
